#!/usr/bin/env node
// Regenerates acp-tools.lock.json — the release-controlled npm documents the
// managed ACP bridge installer replays with `npm ci`.
//
// The lock is npm's *input*, not a grader: for each bridge this script resolves
// the pinned version once, captures the resulting `package.json` +
// `package-lock.json` verbatim (normalizing every `resolved` host to
// registry.npmjs.org so the artifact is portable and carries no internal
// mirror URL), then replays those documents through the exact `npm ci`
// invocation Distill runs — once per supported target triple — to derive and
// smoke-test the per-target native executable path. Nothing here is
// hand-transcribable, so regeneration is always a script run.
import { execFile } from "node:child_process";
import { mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

// Node 20+ refuses to spawn `.cmd` without a shell (EINVAL). Drive npm through
// the bundled `npm-cli.js` on Windows so the lock generator matches a real
// `npm` without going through cmd.exe.
let cachedNpmCliJs = null;

const repoRoot = path.resolve(import.meta.dirname, "..");
const defaultLockFile = path.join(repoRoot, "acp-tools.lock.json");
const nodeRuntimeLockFile = path.join(repoRoot, "node-runtime.lock.json");

// Every `resolved` URL is rewritten to this host before the lock is written:
// the artifact stays portable across registries (npm's default
// `replace-registry-host=npmjs`, which the installer also passes explicitly,
// redirects these fetches to whatever registry is configured) and no internal
// mirror URL lands in a checked-in file.
const CANONICAL_REGISTRY = "https://registry.npmjs.org/";

// The synthetic root package the staged install replays. Its identity is
// arbitrary — npm only needs a root that names the pinned bridge as an exact
// dependency — but it must stay stable, since changing it rewrites both
// documents for every bridge.
const ROOT_NAME = "distill-managed-acp-install";
const ROOT_VERSION = "0.0.0";

// Written verbatim into the artifact so the file explains itself to anyone who
// opens it. The lock is fully generated — this prose lives here, not there.
const LOCK_COMMENT =
  "Release-controlled npm documents for the Distill-managed ACP bridges. Generated by scripts/update-acp-tools-lock.mjs; do not hand-edit. For each bridge, packageJson and packageLock are written into the staged install tree and replayed with 'npm ci' (src-tauri/src/services/managed_acp_tools.rs), so npm resolves TO this pin and refuses any tarball whose integrity differs, and nativeExecutables names the per-target executable that must physically exist before the upgrade commits. Because npm never re-resolves a range here, transitive security patches arrive only when someone regenerates this file: it needs an owner and a refresh cadence.";

// Distill target triple → npm `--os` / `--cpu` / `--libc` selectors. Mirrors
// `npm_target_selectors` in src-tauri/src/services/managed_acp_tools.rs; the
// key set is checked against node-runtime.lock.json's artifacts below, which
// is the one list of targets Distill manages a runtime for.
const TARGET_SELECTORS = {
  "aarch64-apple-darwin": { os: "darwin", cpu: "arm64" },
  "aarch64-unknown-linux-gnu": { os: "linux", cpu: "arm64", libc: "glibc" },
  "x86_64-apple-darwin": { os: "darwin", cpu: "x64" },
  "x86_64-pc-windows-msvc": { os: "win32", cpu: "x64" },
  "x86_64-unknown-linux-gnu": { os: "linux", cpu: "x64", libc: "glibc" },
};

// Tool id → the basename of the vendored agent executable each bridge must be
// able to run. npm records every platform's optional native package in the
// lockfile but materializes only the compatible one, so this is resolved per
// target from a real install rather than assumed.
const NATIVE_EXECUTABLE_BASENAMES = {
  "claude-acp": "claude",
  "codex-acp": "codex",
};

function usage() {
  console.log(`Usage: scripts/update-acp-tools-lock.mjs [<tool-id>[=<npm-package>]@<version> ...] [--lock-file <path>] [--registry <url>]

Regenerates acp-tools.lock.json: resolves each managed ACP bridge once, records
its package.json + package-lock.json (with every 'resolved' host normalized to
${CANONICAL_REGISTRY}), then replays those documents with 'npm ci' for every
supported target to derive and smoke-test the native executable each target
needs.

Without tool arguments every bridge is re-resolved at its currently locked
version (a transitive refresh). Pass '<tool-id>@<version>' to bump one bridge,
or '<tool-id>=<npm-package>@<version>' to add one.

This runs a real install per bridge plus one per supported target: expect a few
minutes and 1-2 GB of temp space. Bump ManagedTool::version in
src-tauri/src/services/managed_acp_tools.rs to match; the embedded-lock test
fails on a mismatch.

Environment:
  ACP_TOOLS_LOCK_FILE  lockfile path override
`);
}

function parseToolArg(arg) {
  const at = arg.lastIndexOf("@");
  if (at <= 0) {
    throw new Error(
      `Expected '<tool-id>[=<npm-package>]@<version>', got: ${arg}`,
    );
  }
  const version = arg.slice(at + 1);
  const left = arg.slice(0, at);
  if (!/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)*$/.test(version)) {
    throw new Error(`Not an exact version: ${arg}`);
  }
  const eq = left.indexOf("=");
  return eq === -1
    ? { id: left, package: null, version }
    : { id: left.slice(0, eq), package: left.slice(eq + 1), version };
}

function parseArgs(argv) {
  let lockFile = process.env.ACP_TOOLS_LOCK_FILE ?? defaultLockFile;
  let registry = null;
  const requested = [];
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "-h" || arg === "--help") {
      usage();
      process.exit(0);
    }
    if (arg === "--lock-file") {
      const value = argv[++i];
      if (!value) throw new Error("--lock-file requires a value");
      lockFile = path.resolve(value);
      continue;
    }
    if (arg === "--registry") {
      const value = argv[++i];
      if (!value) throw new Error("--registry requires a value");
      registry = value;
      continue;
    }
    if (arg.startsWith("-")) throw new Error(`Unknown argument: ${arg}`);
    requested.push(parseToolArg(arg));
  }
  return { lockFile, registry, requested };
}

/** `"v24.11.0"` → `"24"`. */
function nodeMajor(version) {
  return version.replace(/^v/, "").split(".")[0];
}

// npm's lockfile shape is npm-*major*-specific (not patch-specific), and the
// documents this writes are replayed by whatever npm is bundled with the
// running Node. A different patch of the pinned major is a legitimate
// toolchain (this is what actually matters for npm's lockfile format below);
// only a different major is a hard stop. Requiring an exact patch match used
// to make this unrunnable on every machine the repo's own setup scripts
// provision, whenever the fnm/Hermit pin and node-runtime.lock.json's pin
// drifted apart by a patch release.
export function checkPinnedNodeVersion(
  processVersion,
  pinnedVersion,
  warn = console.warn,
) {
  if (processVersion === pinnedVersion) return;
  if (nodeMajor(processVersion) !== nodeMajor(pinnedVersion)) {
    throw new Error(
      `This must run on Node ${nodeMajor(pinnedVersion)}.x: node-runtime.lock.json pins ${pinnedVersion}, this is ${processVersion}`,
    );
  }
  warn(
    `warning: running Node ${processVersion}, but node-runtime.lock.json pins ${pinnedVersion}. ` +
      `Same major (${nodeMajor(pinnedVersion)}.x), so continuing, but the generated lock should ` +
      "ideally come from the exact pinned patch.",
  );
}

async function bundledNpmManifestPath(execPath) {
  const dir = path.dirname(execPath);
  // Windows Node zips keep npm next to node.exe; Unix prefixes keep it under
  // ../lib/node_modules/npm. Distill is Windows-only, but this script still
  // has to locate whichever layout the running Node actually ships.
  const candidates = [
    path.join(dir, "node_modules", "npm", "package.json"),
    path.join(dir, "..", "lib", "node_modules", "npm", "package.json"),
  ];
  for (const candidate of candidates) {
    try {
      await readFile(candidate);
      return candidate;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  throw new Error(
    `Could not find bundled npm next to ${execPath}; looked at:\n  ${candidates.join("\n  ")}`,
  );
}

async function assertPinnedToolchain() {
  const pinned = JSON.parse(await readFile(nodeRuntimeLockFile, "utf8"));
  checkPinnedNodeVersion(process.version, pinned.version);
  const bundled = JSON.parse(
    await readFile(await bundledNpmManifestPath(process.execPath), "utf8"),
  ).version;
  const { stdout } = await runNpm(["--version"]);
  const ambient = stdout.trim();
  const major = (version) => version.split(".")[0];
  if (major(ambient) !== major(bundled)) {
    throw new Error(
      `npm major mismatch: ${process.version} bundles npm ${bundled} but 'npm' on PATH is ${ambient}`,
    );
  }
  return { node: process.version, npm: ambient };
}

// The targets Distill manages a Node runtime for are the targets the installer
// can reach, so the selector table and the native-executable map must cover
// exactly that set.
async function supportedTargets() {
  const pinned = JSON.parse(await readFile(nodeRuntimeLockFile, "utf8"));
  const runtimeTargets = Object.keys(pinned.artifacts).sort();
  const selectorTargets = Object.keys(TARGET_SELECTORS).sort();
  if (runtimeTargets.join(",") !== selectorTargets.join(",")) {
    throw new Error(
      `TARGET_SELECTORS must cover exactly node-runtime.lock.json's targets.\n  runtime:   ${runtimeTargets.join(", ")}\n  selectors: ${selectorTargets.join(", ")}`,
    );
  }
  return runtimeTargets;
}

function registryArgs(registry) {
  return registry ? ["--registry", registry] : [];
}

// The exact `npm ci` invocation the installer runs, mirrored from
// `npm_ci_args` in src-tauri/src/services/managed_acp_tools.rs. Deriving the
// native executable map from anything weaker would not prove the shipped
// install path materializes it.
function npmCiArgs(target, registry) {
  const selectors = TARGET_SELECTORS[target];
  const args = [
    "ci",
    "--prefix",
    ".",
    "--omit=dev",
    "--include=optional",
    "--ignore-scripts",
    "--no-audit",
    "--no-fund",
    "--replace-registry-host=npmjs",
    "--os",
    selectors.os,
    "--cpu",
    selectors.cpu,
  ];
  if (selectors.libc) args.push("--libc", selectors.libc);
  return args.concat(registryArgs(registry));
}

async function runNpm(args, options = {}) {
  let file = "npm";
  let argv = args;
  if (process.platform === "win32") {
    if (!cachedNpmCliJs) {
      cachedNpmCliJs = path.join(
        path.dirname(await bundledNpmManifestPath(process.execPath)),
        "bin",
        "npm-cli.js",
      );
    }
    file = process.execPath;
    argv = [cachedNpmCliJs, ...args];
  }
  return execFileAsync(file, argv, {
    maxBuffer: 64 * 1024 * 1024,
    ...options,
  });
}

async function npm(args, cwd) {
  try {
    return await runNpm(args, { cwd });
  } catch (error) {
    const detail = [error.stdout, error.stderr]
      .filter(Boolean)
      .join("\n")
      .trim();
    throw new Error(
      `npm ${args.join(" ")} failed:\n${detail || error.message}`,
    );
  }
}

async function withTempDir(prefix, body) {
  const dir = await mkdtemp(path.join(os.tmpdir(), prefix));
  try {
    return await body(dir);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

// A lockfile entry's package name: the segment after the final
// `node_modules/` in its path, except for aliased installs (`npm:x@y`), which
// npm records under an alias path with the real name in `name`.
function entryPackageName(key, entry) {
  if (typeof entry.name === "string") return entry.name;
  const at = key.lastIndexOf("node_modules/");
  if (at === -1) throw new Error(`Not a node_modules path: ${key}`);
  return key.slice(at + "node_modules/".length);
}

// Rewrite one `resolved` URL onto the canonical registry. npm's tarball URLs
// are `<registry>/<name>/-/<file>`, and a mirror only varies the prefix, so
// the canonical form is rebuilt from the entry's own name plus the tarball
// filename. A URL that does not have that shape (a git or tarball dependency)
// is not replayable from the canonical registry, so it fails here rather than
// at every user's install.
function canonicalResolved(key, entry) {
  const name = entryPackageName(key, entry);
  const url = new URL(entry.resolved);
  const marker = "/-/";
  const at = url.pathname.lastIndexOf(marker);
  if (at === -1) {
    throw new Error(
      `${key}: 'resolved' is not a registry tarball URL: ${entry.resolved}`,
    );
  }
  const file = url.pathname.slice(at + marker.length);
  // A mirror may serve the same tarball under a path prefix, so only the tail
  // has to match; anything else (a different package name, a nested path)
  // means the rewrite would point at the wrong artifact.
  if (!decodeURIComponent(url.pathname).endsWith(`/${name}/-/${file}`)) {
    throw new Error(
      `${key}: cannot canonicalize 'resolved' ${entry.resolved} for package ${name}`,
    );
  }
  return `${CANONICAL_REGISTRY}${name}/-/${file}`;
}

// npm's `package-lock.json` verbatim, with `resolved` hosts canonicalized,
// `license` dropped, and the properties the installer depends on asserted at
// generation time rather than at every user's install: an exact root version,
// and a version plus SRI integrity on every resolved dependency (a bundled
// dependency carries neither, and would make the graph unverifiable).
//
// `license` is the one field npm does not record deterministically — it
// appears or disappears per entry depending on how much manifest metadata the
// local cache happened to hold — and it is inert for installation. Dropping it
// makes regeneration reproducible, so a reviewer who re-runs this script sees
// only real dependency changes instead of a scatter of cache noise.
function normalizeLock(lock, tool) {
  if (lock.lockfileVersion < 2) {
    throw new Error(
      `${tool.id}: lockfileVersion ${lock.lockfileVersion} has no 'packages' map`,
    );
  }
  const root = lock.packages[""];
  if (root?.dependencies?.[tool.package] !== tool.version) {
    throw new Error(
      `${tool.id}: lock root depends on ${JSON.stringify(root?.dependencies)}, expected an exact ${tool.package}@${tool.version}`,
    );
  }
  const rootEntry = lock.packages[`node_modules/${tool.package}`];
  if (rootEntry?.version !== tool.version) {
    throw new Error(
      `${tool.id}: ${tool.package} resolved to ${rootEntry?.version}, not the requested ${tool.version}`,
    );
  }
  for (const [key, entry] of Object.entries(lock.packages)) {
    if (key === "") continue;
    if (typeof entry.version !== "string") {
      throw new Error(`${tool.id}: lock entry ${key} has no version`);
    }
    if (typeof entry.integrity !== "string") {
      throw new Error(
        `${tool.id}: lock entry ${key} has no integrity (a bundled dependency cannot be verified)`,
      );
    }
    if (typeof entry.resolved !== "string") {
      throw new Error(`${tool.id}: lock entry ${key} has no resolved URL`);
    }
    entry.resolved = canonicalResolved(key, entry);
    delete entry.license;
  }
  return lock;
}

// Resolve one bridge from the registry and capture the two documents npm will
// replay. This is the only free re-resolution in the whole pipeline; every
// later step, and every user install, replays what it produced.
async function resolveTool(tool, registry) {
  return withTempDir(`distill-acp-lock-${tool.id}-`, async (dir) => {
    const packageJson = {
      name: ROOT_NAME,
      version: ROOT_VERSION,
      private: true,
      dependencies: { [tool.package]: tool.version },
    };
    await writeFile(
      path.join(dir, "package.json"),
      `${JSON.stringify(packageJson, null, 2)}\n`,
    );
    await npm(
      [
        "install",
        `${tool.package}@${tool.version}`,
        "--save-exact",
        "--prefix",
        ".",
        "--omit=dev",
        "--include=optional",
        "--ignore-scripts",
        "--no-audit",
        "--no-fund",
        ...registryArgs(registry),
      ],
      dir,
    );
    const lock = JSON.parse(
      await readFile(path.join(dir, "package-lock.json"), "utf8"),
    );
    return { packageJson, packageLock: normalizeLock(lock, tool) };
  });
}

async function walkFiles(dir, relative, out) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      // npm's bin shim directory duplicates every executable name; the pinned
      // path must be the real file inside its own package.
      if (entry.name === ".bin") continue;
      await walkFiles(path.join(dir, entry.name), rel, out);
    } else if (entry.isFile()) {
      out.push(rel);
    }
  }
}

// npm's `os` / `cpu` / `libc` manifest semantics: an empty or absent list
// allows everything, a `!`-prefixed entry excludes, and any other entry is an
// allow-list member.
function fieldAllows(values, actual) {
  if (!Array.isArray(values) || values.length === 0) return true;
  const excluded = values.filter((value) => value.startsWith("!"));
  if (excluded.some((value) => value.slice(1) === actual)) return false;
  const allowed = values.filter((value) => !value.startsWith("!"));
  return allowed.length === 0 || allowed.includes(actual);
}

// npm materializes a native package whose manifest does not match the
// requested target in one real case: `--libc` does not prune a musl variant
// whose `os`/`cpu` match (claude's Linux packages ship both). The pinned path
// must be the variant the target can actually execute, so candidates are
// filtered by their own manifest rather than trusted because npm unpacked
// them.
async function packageMatchesTarget(packageDir, target) {
  const selectors = TARGET_SELECTORS[target];
  let manifest;
  try {
    manifest = JSON.parse(
      await readFile(path.join(packageDir, "package.json"), "utf8"),
    );
  } catch {
    return true;
  }
  if (!fieldAllows(manifest.os, selectors.os)) return false;
  if (!fieldAllows(manifest.cpu, selectors.cpu)) return false;
  return selectors.libc ? fieldAllows(manifest.libc, selectors.libc) : true;
}

// Replay the captured documents through the installer's exact `npm ci` for
// one target, assert npm left the lock untouched (the property that makes the
// installer's post-install graph comparison a tautology rather than a race
// against upstream), and return the single materialized native executable
// this target can run.
async function probeTarget(tool, documents, target, registry) {
  const basename =
    NATIVE_EXECUTABLE_BASENAMES[tool.id] +
    (TARGET_SELECTORS[target].os === "win32" ? ".exe" : "");
  return withTempDir(`distill-acp-probe-${tool.id}-`, async (dir) => {
    const lockText = `${JSON.stringify(documents.packageLock, null, 2)}\n`;
    await writeFile(
      path.join(dir, "package.json"),
      `${JSON.stringify(documents.packageJson, null, 2)}\n`,
    );
    await writeFile(path.join(dir, "package-lock.json"), lockText);
    await npm(npmCiArgs(target, registry), dir);
    const replayed = await readFile(
      path.join(dir, "package-lock.json"),
      "utf8",
    );
    if (replayed !== lockText) {
      throw new Error(
        `${tool.id}: 'npm ci' rewrote package-lock.json for ${target}; the captured document is not replayable`,
      );
    }
    const files = [];
    await walkFiles(path.join(dir, "node_modules"), "node_modules", files);
    const named = files.filter(
      (file) => path.posix.basename(file) === basename,
    );
    const owner = (file) =>
      Object.keys(documents.packageLock.packages)
        .filter((key) => key !== "" && file.startsWith(`${key}/`))
        .sort((a, b) => b.length - a.length)[0];
    const matches = [];
    for (const file of named) {
      const key = owner(file);
      if (!key) {
        throw new Error(
          `${tool.id}: '${file}' for ${target} is not inside any locked package`,
        );
      }
      if (await packageMatchesTarget(path.join(dir, key), target)) {
        matches.push(file);
      }
    }
    if (matches.length !== 1) {
      throw new Error(
        `${tool.id}: expected exactly one ${target}-compatible '${basename}' under node_modules, found ${matches.length} of ${named.length} candidate(s)${named.length ? `:\n  ${named.join("\n  ")}` : ""}`,
      );
    }
    return matches[0];
  });
}

function sortedByKey(object) {
  return Object.fromEntries(
    Object.entries(object).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  );
}

// Report every resolved version this run changed, so the reviewer reads a
// version list rather than a wall of integrity hashes.
function reportVersionDiff(id, previous, next) {
  const versions = (lock) =>
    new Map(
      Object.entries(lock?.packages ?? {})
        .filter(([key]) => key !== "")
        .map(([key, entry]) => [key, entry.version]),
    );
  const before = versions(previous);
  const after = versions(next);
  const lines = [];
  for (const [key, version] of after) {
    const was = before.get(key);
    if (was === undefined) lines.push(`  + ${key}@${version}`);
    else if (was !== version) lines.push(`  ~ ${key} ${was} -> ${version}`);
  }
  for (const key of before.keys()) {
    if (!after.has(key)) lines.push(`  - ${key}@${before.get(key)}`);
  }
  console.log(
    lines.length
      ? `${id}: ${after.size} resolved packages, ${lines.length} changed\n${lines.join("\n")}`
      : `${id}: ${after.size} resolved packages, unchanged`,
  );
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const toolchain = await assertPinnedToolchain();
  const targets = await supportedTargets();
  const existing = JSON.parse(await readFile(args.lockFile, "utf8"));

  const tools = Object.entries(existing.tools).map(([id, entry]) => ({
    id,
    package: entry.package,
    version: entry.version,
  }));
  for (const requested of args.requested) {
    const found = tools.find((tool) => tool.id === requested.id);
    if (found) {
      found.version = requested.version;
      if (requested.package) found.package = requested.package;
    } else if (requested.package) {
      tools.push(requested);
    } else {
      throw new Error(
        `Unknown tool '${requested.id}'; pass '<tool-id>=<npm-package>@<version>' to add it`,
      );
    }
  }
  for (const tool of tools) {
    if (!NATIVE_EXECUTABLE_BASENAMES[tool.id]) {
      throw new Error(
        `No native executable basename for '${tool.id}'; add one to NATIVE_EXECUTABLE_BASENAMES`,
      );
    }
  }

  console.log(
    `Resolving ${tools.length} bridge(s) on node ${toolchain.node} / npm ${toolchain.npm}`,
  );
  const resolved = {};
  for (const tool of tools.sort((a, b) => (a.id < b.id ? -1 : 1))) {
    console.log(`\n${tool.id}: resolving ${tool.package}@${tool.version}`);
    const documents = await resolveTool(tool, args.registry);
    reportVersionDiff(
      tool.id,
      existing.tools[tool.id]?.packageLock,
      documents.packageLock,
    );
    const nativeExecutables = {};
    for (const target of targets) {
      console.log(`${tool.id}: replaying with npm ci for ${target}`);
      nativeExecutables[target] = await probeTarget(
        tool,
        documents,
        target,
        args.registry,
      );
      console.log(`  ${nativeExecutables[target]}`);
    }
    resolved[tool.id] = {
      package: tool.package,
      version: tool.version,
      nativeExecutables: sortedByKey(nativeExecutables),
      packageJson: documents.packageJson,
      packageLock: documents.packageLock,
    };
  }

  await writeFile(
    args.lockFile,
    `${JSON.stringify({ $comment: LOCK_COMMENT, tools: sortedByKey(resolved) }, null, 2)}\n`,
  );
  console.log(
    `\nWrote ${path.relative(process.cwd(), args.lockFile)}. Bump ManagedTool::version in src-tauri/src/services/managed_acp_tools.rs to match, then run 'cargo test --manifest-path src-tauri/Cargo.toml managed_acp_tools'.`,
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  });
}
