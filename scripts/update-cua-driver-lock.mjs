#!/usr/bin/env node
// Pin a Cua Driver release for Flock's computer use: writes cua-driver.lock.json.
//
// The archive SHA-256 written here is what src-tauri/src/services/computer_use/
// install.rs trusts at install time, so this script checks it four ways before
// writing it: GitHub's digest of the release asset, the release's own
// checksums.txt, the Sigstore signature over the archive, and the signing
// certificate's identity, which must be the release workflow at the release
// tag. When `cosign` is on PATH it also verifies the certificate chain and the
// transparency-log entry; without it the script says that part was skipped.
import { spawnSync } from "node:child_process";
import { createHash, verify, X509Certificate } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";

const repoRoot = path.resolve(import.meta.dirname, "..");
const defaultLockFile = path.join(repoRoot, "cua-driver.lock.json");
const REPO = "trycua/cua";
const WORKFLOW = ".github/workflows/cd-rust-cua-driver.yml";
const OIDC_ISSUER = "https://token.actions.githubusercontent.com";

// Rust target triple → the platform part of the release archive name.
const TARGETS = {
  "x86_64-pc-windows-msvc": "windows-x86_64",
};

// The only files Flock takes out of the archive.
const FILES = ["cua-driver.exe", "LICENSE", "THIRD_PARTY_NOTICES.md"];

const COMMENT =
  "Release pin for the Cua Driver that Flock runs for chats with computer use on. Generated by scripts/update-cua-driver-lock.mjs; do not hand-edit. The archive SHA-256 is the trust root at install time (src-tauri/src/services/computer_use/install.rs). The script checks it against the release's checksums.txt and the release's Sigstore bundle, whose certificate must name the signer workflow below, before it writes this file.";

function usage() {
  console.log(`Usage: scripts/update-cua-driver-lock.mjs [version] [--lock-file <path>]

Pins a trycua/cua Cua Driver release (tag cua-driver-rs-v<version>) in
cua-driver.lock.json after checking the Windows archive's checksum and
Sigstore signature. Without a version, the locked one is checked again.

Environment:
  GITHUB_TOKEN  optional, raises the GitHub API rate limit
`);
}

function parseArgs(argv) {
  let version = null;
  let lockFile = defaultLockFile;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "-h" || arg === "--help") {
      usage();
      process.exit(0);
    } else if (arg === "--lock-file") {
      lockFile = path.resolve(argv[++i] ?? "");
    } else if (!arg.startsWith("-") && version === null) {
      version = arg.replace(/^v/, "");
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  if (version !== null && !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(`Invalid Cua Driver version: ${version}`);
  }
  return { version, lockFile };
}

async function fetchOk(url, accept) {
  const headers = { "User-Agent": "flock-lock-updater", Accept: accept };
  if (process.env.GITHUB_TOKEN && url.startsWith("https://api.github.com/")) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }
  const response = await fetch(url, { headers, redirect: "follow" });
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status}`);
  }
  return response;
}

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** The entry names in a zip archive, read from its central directory. */
export function zipEntryNames(bytes) {
  const end = bytes.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (end < 0) {
    throw new Error("The archive is not a zip file");
  }
  const count = bytes.readUInt16LE(end + 10);
  let offset = bytes.readUInt32LE(end + 16);
  const names = [];
  for (let index = 0; index < count; index += 1) {
    if (bytes.readUInt32LE(offset) !== 0x02014b50) {
      throw new Error("The archive's central directory is damaged");
    }
    const nameLength = bytes.readUInt16LE(offset + 28);
    const extraLength = bytes.readUInt16LE(offset + 30);
    const commentLength = bytes.readUInt16LE(offset + 32);
    names.push(bytes.toString("utf8", offset + 46, offset + 46 + nameLength));
    offset += 46 + nameLength + extraLength + commentLength;
  }
  return names;
}

/** Check the legacy cosign bundle the release ships beside each archive. */
export function checkSigstoreBundle(bundle, archive, signer) {
  const pem = Buffer.from(bundle.cert, "base64").toString("utf8");
  const certificate = new X509Certificate(pem);
  const identities = (certificate.subjectAltName ?? "").split(/,\s*/);
  if (!identities.includes(`URI:${signer}`)) {
    throw new Error(
      `The signing certificate names ${certificate.subjectAltName}, not ${signer}`,
    );
  }
  const signature = Buffer.from(bundle.base64Signature, "base64");
  if (!verify("sha256", archive, certificate.publicKey, signature)) {
    throw new Error("The Sigstore signature does not match the archive");
  }
  const entry = JSON.parse(
    Buffer.from(bundle.rekorBundle.Payload.body, "base64").toString("utf8"),
  );
  const logged = entry?.spec?.data?.hash?.value;
  if (logged !== sha256(archive)) {
    throw new Error(
      `The transparency-log entry records ${logged}, not this archive`,
    );
  }
  const signedAt = new Date(bundle.rekorBundle.Payload.integratedTime * 1000);
  if (
    signedAt < new Date(certificate.validFrom) ||
    signedAt > new Date(certificate.validTo)
  ) {
    throw new Error(
      "The archive was logged outside the certificate's validity",
    );
  }
}

function cosignVerify(archivePath, bundlePath, signer) {
  const probe = spawnSync("cosign", ["version"], { stdio: "ignore" });
  if (probe.error || probe.status !== 0) {
    return false;
  }
  const result = spawnSync(
    "cosign",
    [
      "verify-blob",
      "--bundle",
      bundlePath,
      "--certificate-identity",
      signer,
      "--certificate-oidc-issuer",
      OIDC_ISSUER,
      archivePath,
    ],
    { stdio: "inherit" },
  );
  if (result.status !== 0) {
    throw new Error("cosign verify-blob refused the archive");
  }
  return true;
}

async function main() {
  const { version: requested, lockFile } = parseArgs(process.argv.slice(2));
  const current = JSON.parse(
    await readFile(lockFile, "utf8").catch(() => "{}"),
  );
  const version = requested ?? current.version;
  if (!version) {
    throw new Error("No version given and no lock to read one from");
  }
  const release = `cua-driver-rs-v${version}`;
  const signer = `https://github.com/${REPO}/${WORKFLOW}@refs/tags/${release}`;
  const metadata = await (
    await fetchOk(
      `https://api.github.com/repos/${REPO}/releases/tags/${release}`,
      "application/vnd.github+json",
    )
  ).json();
  const tag = await (
    await fetchOk(
      `https://api.github.com/repos/${REPO}/commits/${release}`,
      "application/vnd.github+json",
    )
  ).json();
  const repository = await (
    await fetchOk(
      `https://api.github.com/repos/${REPO}`,
      "application/vnd.github+json",
    )
  ).json();
  const license = repository.license?.spdx_id;
  if (!license || license === "NOASSERTION") {
    throw new Error(`${REPO} declares no licence GitHub recognises`);
  }
  const assets = new Map(metadata.assets.map((asset) => [asset.name, asset]));
  const download = async (name) => {
    const asset = assets.get(name);
    if (!asset) {
      throw new Error(`${release} has no ${name}`);
    }
    const bytes = Buffer.from(
      await (
        await fetchOk(asset.browser_download_url, "application/octet-stream")
      ).arrayBuffer(),
    );
    return { asset, bytes };
  };
  const checksums = (await download("checksums.txt")).bytes.toString("utf8");

  const artifacts = {};
  for (const [target, platform] of Object.entries(TARGETS)) {
    const name = `cua-driver-rs-${version}-${platform}.zip`;
    const { asset, bytes } = await download(name);
    const digest = sha256(bytes);
    if (asset.digest && asset.digest !== `sha256:${digest}`) {
      throw new Error(
        `${name}: GitHub reports ${asset.digest}, the download is ${digest}`,
      );
    }
    const listed = checksums
      .split(/\r?\n/)
      .map((line) => line.trim().split(/\s+\*?/))
      .find(([, file]) => file === name)?.[0];
    if (listed !== digest) {
      throw new Error(
        `${name}: checksums.txt lists ${listed ?? "nothing"}, the download is ${digest}`,
      );
    }
    const bundleBytes = (await download(`${name}.sigstore.json`)).bytes;
    checkSigstoreBundle(
      JSON.parse(bundleBytes.toString("utf8")),
      bytes,
      signer,
    );

    const prefix = `cua-driver-rs-${version}-${platform}`;
    const entries = new Set(zipEntryNames(bytes));
    const missing = FILES.filter((file) => !entries.has(`${prefix}/${file}`));
    if (missing.length > 0) {
      throw new Error(`${name} lacks ${missing.join(", ")} under ${prefix}/`);
    }

    const scratch = path.join(os.tmpdir(), `flock-cua-${process.pid}`);
    await mkdir(scratch, { recursive: true });
    const archivePath = path.join(scratch, name);
    const bundlePath = `${archivePath}.sigstore.json`;
    await writeFile(archivePath, bytes);
    await writeFile(bundlePath, bundleBytes);
    let fullyVerified;
    try {
      fullyVerified = cosignVerify(archivePath, bundlePath, signer);
    } finally {
      await rm(scratch, { recursive: true, force: true });
    }
    console.log(
      fullyVerified
        ? `${name}: checksum, signature, signer and transparency log verified (cosign)`
        : `${name}: checksum, signature and signer verified; install cosign to also verify the certificate chain and the transparency log`,
    );

    artifacts[target] = {
      url: asset.browser_download_url,
      sha256: digest,
      size: bytes.length,
      files: Object.fromEntries(
        FILES.map((file) => [file, `${prefix}/${file}`]),
      ),
    };
  }

  const lock = {
    $comment: COMMENT,
    version,
    release,
    sourceCommit: tag.sha,
    signer,
    license,
    artifacts,
  };
  await writeFile(lockFile, `${JSON.stringify(lock, null, 2)}\n`);
  console.log(
    `Wrote ${path.relative(repoRoot, lockFile)} for Cua Driver ${version}`,
  );
  console.log(
    "Then run the computer use tests: just _tauri-cargo-windows test --lib -- computer_use",
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
